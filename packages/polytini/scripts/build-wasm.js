// Assembles wasm/polytini.wat into wasm/polytini.wasm and inlines it as
// base64 in src/wasm-bytes.js, so the /wasm entry needs no fetch or fs.
//   node scripts/build-wasm.js
import { readFileSync, writeFileSync } from 'node:fs';
import wabt from 'wabt';

const dir = new URL('../', import.meta.url);
const w = await wabt();
const mod = w.parseWat('polytini.wat', readFileSync(new URL('wasm/polytini.wat', dir), 'utf8'));
mod.resolveNames();
mod.validate();
const { buffer } = mod.toBinary({ write_debug_names: false });
mod.destroy();
writeFileSync(new URL('wasm/polytini.wasm', dir), buffer);
writeFileSync(
  new URL('src/wasm-bytes.js', dir),
  `// Generated by scripts/build-wasm.js from wasm/polytini.wat. Do not edit.\nexport default '${Buffer.from(buffer).toString('base64')}';\n`,
);
console.log(`wasm/polytini.wasm: ${buffer.length} bytes`);
